"""Financial health indicator: /financial-health"""

from __future__ import annotations

from nicegui import ui

from app.auth.session import current_user, login_redirect
from app.components import charts
from app.components.app_shell import app_shell
from app.components.dashboard_cards import empty_state, page_header, panel, progress_bar
from app.database import insight_repository
from app.services.health_service import BANDS, compute_health, weakest_factors
from app.services.transaction_service import transactions_dataframe
from app.styles.theme import COLORS


def _score_color(score: float) -> str:
    if score >= 80:
        return COLORS["mint"]
    if score >= 60:
        return COLORS["iris"]
    if score >= 30:
        return COLORS["amber"]
    return COLORS["coral"]


@ui.page("/financial-health", title="Financial Health · FinTwin AI")
def financial_health_page():
    user = current_user()
    if user is None:
        return login_redirect("/financial-health")

    with app_shell(user, "health"):
        page_header("Financial health",
                    "A transparent, rule-based indicator built from seven factors. It's an estimate generated by "
                    "this app, not a credit score or professional assessment.",
                    lambda: ui.button("Add missing details", icon="tune",
                                      on_click=lambda: ui.navigate.to("/settings")).classes("ft-btn-ghost").props("color=none text-color=none"))
        report = compute_health(transactions_dataframe(user.id), insight_repository.get_profile(user.id))
        if not report.available:
            with panel():
                empty_state("Not enough data yet", " ".join(report.notes), "monitor_heart",
                            lambda: ui.button("Add transactions", on_click=lambda: ui.navigate.to("/transactions")).classes(
                                "ft-btn-primary").props("color=none text-color=none"))
            return None

        with ui.element("div").classes("grid gap-4 lg:grid-cols-[minmax(0,1fr)_minmax(0,1.4fr)] w-full"):
            with panel("Your indicator", f"Based on the last {report.months_analyzed} completed month(s)"):
                charts.render(charts.health_gauge(report.score, report.color, 230))
                with ui.row().classes("w-full justify-center -mt-2"):
                    ui.label(f"About {report.score} · {report.band}").classes("ft-display text-lg font-semibold").style(
                        f"color:{report.color}")
                ui.label("Rounded to the nearest 5, because the method is a heuristic rather than a precise "
                         "measurement.").classes("text-xs ft-muted text-center w-full")
                with ui.element("div").classes("grid grid-cols-4 gap-2 w-full mt-2"):
                    for low, high, label, color in BANDS:
                        active = low <= report.score <= high
                        with ui.column().classes("gap-1 items-center p-2 rounded-xl").style(
                            f"background:{color}{'26' if active else '0D'}; border:1px solid {color}{'66' if active else '1A'}"
                        ):
                            ui.label(f"{low}–{high}").classes("text-xs ft-num font-semibold").style(f"color:{color}")
                            ui.label(label).classes("text-[11px] ft-muted text-center leading-tight")

            with panel("What would help most", "Your two lowest-scoring factors"):
                for f in weakest_factors(report, 2):
                    with ui.column().classes("ft-tile p-4 gap-2 w-full"):
                        with ui.row().classes("w-full justify-between items-center no-wrap"):
                            ui.label(f.name).classes("font-semibold")
                            ui.label(f"{f.score}/100").classes("ft-num text-sm font-semibold").style(
                                f"color:{_score_color(f.score)}")
                        ui.label(f.value_text).classes("text-sm ft-muted")
                        with ui.row().classes("gap-2 no-wrap items-start"):
                            ui.icon("tips_and_updates", size="18px").classes("ft-iris mt-0.5")
                            ui.label(f.tip).classes("text-sm")
                if report.notes:
                    with ui.column().classes("gap-1 w-full"):
                        for note in report.notes:
                            with ui.row().classes("gap-2 no-wrap items-start"):
                                ui.icon("info", size="16px").classes("ft-amber mt-0.5")
                                ui.label(note).classes("text-xs ft-muted")

        with panel("All factors", "Each factor's rule, weight and your sub-score"):
            with ui.element("div").classes("grid gap-3 md:grid-cols-2 w-full"):
                for f in report.factors:
                    color = _score_color(f.score)
                    with ui.column().classes("ft-tile p-4 gap-2"):
                        with ui.row().classes("w-full justify-between items-center no-wrap"):
                            with ui.row().classes("items-center gap-2"):
                                ui.label(f.name).classes("font-semibold")
                                if f.estimated:
                                    ui.label("Estimated").classes("ft-chip ft-chip-amber").tooltip(
                                        "Some input was missing, see notes above")
                            ui.label(f"{f.score}").classes("ft-num text-xl font-bold").style(f"color:{color}")
                        progress_bar(f.score, color)
                        with ui.row().classes("w-full justify-between text-xs"):
                            ui.label(f.value_text).classes("ft-muted")
                            ui.label(f"Weight {f.weight * 100:.0f}%").classes("ft-faint")
                        ui.label(f.rule).classes("text-xs ft-faint")

        with ui.row().classes("ft-tile p-4 gap-3 no-wrap items-start w-full"):
            ui.icon("science", size="20px").classes("ft-iris mt-0.5")
            ui.label("How it's calculated: each factor is scored 0–100 by the rule shown, multiplied by its weight, "
                     "and summed. Thresholds (e.g. 30% savings rate, 6 months of emergency fund) are common rules of "
                     "thumb, not personalised advice.").classes("text-sm ft-muted")
    return None
